// Embeds skills/** into lib/skills.generated.ts with SHA-256 digests and byte sizes (SEP-2640 manifest).
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const skillsDir = join(root, 'skills');

function walk(dir) {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

// Minimal YAML frontmatter reader for Agent Skills: scalars, quoted strings and folded/literal blocks.
// Rejects anything it cannot represent exactly, because hosts compare frontmatter field by field (SEP-2640).
function frontmatter(text) {
  if (text.includes('\r')) throw new Error('SKILL.md must use LF line endings');
  const m = text.match(/^---\n([\s\S]*?)\n---\n/);
  if (!m) throw new Error('SKILL.md without frontmatter');
  const fm = {};
  const lines = m[1].split('\n');
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (!line.trim() || line.trimStart().startsWith('#')) continue;
    const kv = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!kv) throw new Error(`Unsupported frontmatter line: ${line}`);
    let [, key, value] = kv;
    if (value === '|' || value === '>') {
      const block = [];
      while (i + 1 < lines.length && /^\s+/.test(lines[i + 1])) block.push(lines[++i].trim());
      value = value === '|' ? block.join('\n') : block.join(' ');
    } else if (/^".*"$/.test(value)) value = JSON.parse(value);
    else if (/^'.*'$/.test(value)) value = value.slice(1, -1).replace(/''/g, "'");
    else if (/^[\[{]/.test(value)) throw new Error(`Frontmatter key ${key}: flow collections are not supported`);
    fm[key] = value;
  }
  for (const k of ['name', 'description']) if (!fm[k]) throw new Error(`Frontmatter needs ${k}`);
  return fm;
}

const skills = [];
for (const name of readdirSync(skillsDir).sort()) {
  const dir = join(skillsDir, name);
  if (!statSync(dir).isDirectory()) continue;
  const files = walk(dir).sort((a, b) => (a.endsWith('SKILL.md') ? -1 : b.endsWith('SKILL.md') ? 1 : a.localeCompare(b)));
  const skillMd = readFileSync(join(dir, 'SKILL.md'), 'utf8');
  const fm = frontmatter(skillMd);
  if (fm.name !== name) throw new Error(`frontmatter name ${fm.name} != dir ${name}`);
  skills.push({
    name,
    frontmatter: fm,
    files: files.map((f) => {
      const buf = readFileSync(f);
      return {
        path: relative(dir, f).split('\\').join('/'),
        text: buf.toString('utf8'),
        size: buf.length,
        digest: 'sha256:' + createHash('sha256').update(buf).digest('hex'),
      };
    }),
  });
}

writeFileSync(
  join(root, 'lib/skills.generated.ts'),
  `// GENERATED by scripts/build-skills.mjs — do not edit. Source: skills/**\n` +
    `export type SkillFile = { path: string; text: string; size: number; digest: string };\n` +
    `export type Skill = { name: string; frontmatter: Record<string, string>; files: SkillFile[] };\n` +
    `export const SKILLS: Skill[] = ${JSON.stringify(skills, null, 2)};\n`,
);
console.log(`embedded ${skills.length} skill(s): ${skills.map((s) => `${s.name}(${s.files.length} files)`).join(', ')}`);
